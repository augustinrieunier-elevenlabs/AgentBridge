"""
Persists Benchmark RUN RESULTS (aggregated latency stats per variant/node) to
<instance>/benchmark_runs.json -- separate from config.json's `benchmarks` array, which only
holds the user-authored benchmark definitions (name, agents, scenarios, variants to test), edited
like any other settings panel. A run is generated by actually executing calls, never edited by
hand, and needs to persist across sessions for future comparison (spec: "persister localement pour
les comparaisons futures") -- same rationale as exports/ for session recordings.
"""
import json
import os
import time
import uuid

from services.config_store import _strip_secret_like


def _runs_path(instance_path):
    return os.path.join(instance_path, "benchmark_runs.json")


def list_runs(instance_path, benchmark_id=None):
    try:
        with open(_runs_path(instance_path), "r", encoding="utf-8") as f:
            runs = json.load(f)
    except FileNotFoundError:
        return []
    if benchmark_id:
        runs = [r for r in runs if r.get("benchmarkId") == benchmark_id]
    return sorted(runs, key=lambda r: r.get("finishedAt") or 0, reverse=True)


def save_run(instance_path, run):
    os.makedirs(instance_path, exist_ok=True)
    path = _runs_path(instance_path)
    try:
        with open(path, "r", encoding="utf-8") as f:
            runs = json.load(f)
    except FileNotFoundError:
        runs = []

    safe_run = _strip_secret_like(run)
    # A plain millisecond timestamp can collide on two fast successive saves (seen in testing) --
    # the suffix guarantees uniqueness without needing to check against existing ids.
    safe_run.setdefault("id", f"run-{int(time.time() * 1000)}-{uuid.uuid4().hex[:8]}")
    safe_run.setdefault("finishedAt", time.time())
    runs.append(safe_run)

    with open(path, "w", encoding="utf-8") as f:
        json.dump(runs, f, indent=2, ensure_ascii=False)
    return safe_run


def update_run(instance_path, run_id, patch):
    """Merges `patch` into an existing run -- used to replace `variants` with freshly re-aggregated
    stats once the platform has finished finalizing conversation_turn_metrics for its conversations
    (not always ready within the short retry window a run's own live collection step uses -- see
    BenchmarkRunner.js refreshRunStats, wired to the Session "Refresh stats" button). Returns the
    updated run, or None if no run with that id exists."""
    path = _runs_path(instance_path)
    try:
        with open(path, "r", encoding="utf-8") as f:
            runs = json.load(f)
    except FileNotFoundError:
        return None

    safe_patch = _strip_secret_like(patch)
    updated = None
    for i, run in enumerate(runs):
        if run.get("id") == run_id:
            runs[i] = {**run, **safe_patch}
            updated = runs[i]
            break
    if updated is None:
        return None

    with open(path, "w", encoding="utf-8") as f:
        json.dump(runs, f, indent=2, ensure_ascii=False)
    return updated


def delete_run(instance_path, run_id):
    path = _runs_path(instance_path)
    try:
        with open(path, "r", encoding="utf-8") as f:
            runs = json.load(f)
    except FileNotFoundError:
        return
    runs = [r for r in runs if r.get("id") != run_id]
    with open(path, "w", encoding="utf-8") as f:
        json.dump(runs, f, indent=2, ensure_ascii=False)


def clear_runs(instance_path):
    """Deletes every saved benchmark run -- used by History's "Clear history" button. Irreversible;
    the UI is expected to confirm before calling this. Deliberately leaves
    benchmark_pending_restores.json untouched: that file tracks a callee agent that may genuinely
    still need restoring to a pre-run config, which "clearing history" has no bearing on."""
    os.makedirs(instance_path, exist_ok=True)
    with open(_runs_path(instance_path), "w", encoding="utf-8") as f:
        json.dump([], f, indent=2, ensure_ascii=False)


def _pending_restores_path(instance_path):
    return os.path.join(instance_path, "benchmark_pending_restores.json")


def _agent_key(account_id, agent_id):
    return f"{account_id}:{agent_id}"


def _load_pending_restores(instance_path):
    try:
        with open(_pending_restores_path(instance_path), "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return {}


def save_pending_restore(instance_path, account_id, agent_id, snapshot):
    """Durably records a callee agent's config as "needs restoring to this" -- written BEFORE a
    benchmark run mutates the agent's live TTS/LLM, not after. If the run is then interrupted
    (crash, navigating away mid-run -- the exact incident that silently left a real agent stuck on
    a broken LLM for several benchmark runs in a row, 2026-10-03, since each run's own `finally`
    only restores to whatever it saw at ITS OWN start -- which was already the prior run's
    unrecovered mutation, so the corruption just propagated forward with nothing to catch it), this
    record survives in a file, independent of the JS process that was running the benchmark, and
    can be found and applied on a later visit (see get_pending_restore / clear_pending_restore and
    BenchmarkSession.jsx's startup check)."""
    os.makedirs(instance_path, exist_ok=True)
    restores = _load_pending_restores(instance_path)
    restores[_agent_key(account_id, agent_id)] = {**snapshot, "recordedAt": time.time()}
    with open(_pending_restores_path(instance_path), "w", encoding="utf-8") as f:
        json.dump(restores, f, indent=2, ensure_ascii=False)


def get_pending_restore(instance_path, account_id, agent_id):
    return _load_pending_restores(instance_path).get(_agent_key(account_id, agent_id))


def clear_pending_restore(instance_path, account_id, agent_id):
    """Removes the pending-restore record -- call ONLY after confirming the restore actually
    happened (e.g. after a successful setModelConfig call), never speculatively, or a second
    interrupted run right after a first one would have nothing left to recover from."""
    restores = _load_pending_restores(instance_path)
    key = _agent_key(account_id, agent_id)
    if key in restores:
        del restores[key]
        os.makedirs(instance_path, exist_ok=True)
        with open(_pending_restores_path(instance_path), "w", encoding="utf-8") as f:
            json.dump(restores, f, indent=2, ensure_ascii=False)
